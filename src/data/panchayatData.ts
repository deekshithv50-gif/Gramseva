/**
 * Filter Gram Panchayats by district and taluk with case-insensitive and partial match fallback
 */
export function getGramPanchayatsByDistrictAndTaluk(
  districtEn: string,
  talukEn: string
): GramPanchayatInfo[] {
  const normDist = districtEn.toLowerCase().trim();
  const normTaluk = talukEn.toLowerCase().trim();

  // Exact or contains match
  const matched = PANCHAYAT_DIRECTORY.filter((gp) => {
    const distMatches =
      gp.districtEn.toLowerCase().includes(normDist) ||
      normDist.includes(gp.districtEn.toLowerCase());
    const talukMatches =
      gp.talukEn.toLowerCase().includes(normTaluk) ||
      normTaluk.includes(gp.talukEn.toLowerCase());
    return distMatches && talukMatches;
  });

  if (matched.length > 0) return matched;

  // If no exact match for taluk, fallback to any GP in that district
  const districtMatched = PANCHAYAT_DIRECTORY.filter((gp) =>
    gp.districtEn.toLowerCase().includes(normDist) ||
    normDist.includes(gp.districtEn.toLowerCase())
  );
  if (districtMatched.length > 0) return districtMatched;

  // Fallback to default
  return [DEFAULT_GRAM_PANCHAYAT];
}

/**
 * Generate standard constituent villages for a newly declared Gram Panchayat (<10 constituent villages)
 */
export function createCustomGramPanchayat(
  gpName: string,
  districtEn: string,
  districtKn: string,
  talukEn: string,
  talukKn: string,
  customVillageNames?: string[]
): GramPanchayatInfo {
  const cleanName = gpName.replace(/gram panchayat/i, '').replace(/ಗ್ರಾಮ ಪಂಚಾಯತಿ/g, '').trim();
  const slug = cleanName.toUpperCase().replace(/[^A-Z0-9]/g, '').slice(0, 4) || 'GP';
  const id = `GP-KA-${slug}-${Math.floor(100 + Math.random() * 900)}`;

  const villageList = (customVillageNames && customVillageNames.length > 0
    ? customVillageNames.slice(0, 7)
    : [
        `${cleanName} Village (Main)`,
        `${cleanName} Cross`,
        `${cleanName} Colony`,
        `${cleanName} Kaval`,
        `${cleanName} Hosahalli`,
      ]
  ).map((name, i) => ({
    id: `VIL-${id}-${i + 1}`,
    nameEn: name,
    nameKn: `${name} (ಗ್ರಾಮ)`,
    population: 1200 + (i * 450),
    wardsCount: (i % 2 === 0 ? 2 : 1),
  }));

  return {
    id,
    nameEn: `${cleanName} Gram Panchayat`,
    nameKn: `${cleanName} ಗ್ರಾಮ ಪಂಚಾಯತಿ`,
    districtEn,
    districtKn,
    talukEn,
    talukKn,
    helplineNumber: '0000111101',
    pdoName: `Sri B. Kumar (PDO, ${cleanName})`,
    pdoPhone: '+91 94480 00101',
    currentTerm: '2021 - 2026 (14th Panchayat Term)',
    nextElectionYear: 2026,
    villages: villageList,
  };
}

